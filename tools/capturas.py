from playwright.sync_api import sync_playwright
import json
C='entregables/capturas/'
with sync_playwright() as p:
    b = p.chromium.launch(args=['--use-gl=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'])
    pg = b.new_page(viewport={'width':1280,'height':720})
    errs=[]
    pg.on('pageerror', lambda e: errs.append('PAGEERROR '+str(e)))
    pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(5000)
    pg.screenshot(path=C+'01_portada.png')
    pg.click('#btnComenzar'); pg.wait_for_timeout(600)
    pg.fill('#regNombre','Elio'); pg.fill('#regDni','1234'); pg.wait_for_timeout(200)
    pg.screenshot(path=C+'02_registro_dni_invalido.png')
    pg.fill('#regDni','12345678'); pg.check('input[name=sexo][value=M]'); pg.wait_for_timeout(300)
    pg.evaluate("H.pantallas.repetir('Viva el Perú, rumbo a Iquique')"); pg.wait_for_timeout(500)
    pg.screenshot(path=C+'03_registro_voz_masculina.png')
    pg.check('input[name=sexo][value=F]'); pg.evaluate("H.pantallas.repetir('Viva el Perú, rumbo a Iquique')"); pg.wait_for_timeout(500)
    pg.screenshot(path=C+'04_registro_voz_femenina.png')
    pg.check('input[name=sexo][value=M]'); pg.click('#btnRegOk'); pg.wait_for_timeout(2500)
    pg.screenshot(path=C+'05_menu.png')
    pg.click('[data-ver=pHistoria]'); pg.wait_for_timeout(500); pg.screenshot(path=C+'06_historia.png'); pg.click('#pHistoria .volver')
    pg.click('[data-ver=pControles]'); pg.wait_for_timeout(500); pg.screenshot(path=C+'07_controles.png'); pg.click('#pControles .volver')
    pg.click('[data-ver=pCreditos]'); pg.wait_for_timeout(500); pg.screenshot(path=C+'08_creditos.png'); pg.click('#pCreditos .volver')
    pg.click('[data-ir="1P"]'); pg.wait_for_timeout(700); pg.screenshot(path=C+'09_briefing_nivel1.png')
    pg.keyboard.press('Enter'); pg.wait_for_timeout(1500)
    pg.keyboard.down('KeyW'); pg.mouse.move(760,250); pg.wait_for_timeout(9000)
    for i in range(3): pg.mouse.click(760+i*10,250); pg.wait_for_timeout(1400)
    pg.keyboard.press('F2'); pg.mouse.click(770,250); pg.wait_for_timeout(500)
    pg.screenshot(path=C+'10_nivel1_iquique_panelQA.png')
    pg.keyboard.press('F2'); pg.keyboard.press('KeyE'); pg.wait_for_timeout(1500); pg.screenshot(path=C+'11_nivel1_espolon.png')
    pg.keyboard.press('KeyP'); pg.wait_for_timeout(500); pg.screenshot(path=C+'12_pausa.png')
    print('pausa', pg.evaluate('H.estado'))
    pg.click('#btnSalir'); pg.wait_for_timeout(800)
    pg.check('input[name=nivelIni][value="1"]'); pg.click('[data-ir="2P"]'); pg.wait_for_timeout(600); pg.screenshot(path=C+'13_briefing_nivel2.png')
    pg.keyboard.press('Enter'); pg.wait_for_timeout(1500); pg.keyboard.down('KeyW'); pg.keyboard.down('ArrowUp'); pg.keyboard.down('KeyQ'); pg.wait_for_timeout(2500); pg.keyboard.up('KeyQ')
    pg.evaluate("H.debug.pasos=6"); pg.wait_for_timeout(5000); pg.evaluate("H.debug.pasos=1")
    pg.keyboard.press('Space'); pg.keyboard.press('Enter'); pg.wait_for_timeout(900)
    pg.screenshot(path=C+'14_nivel2_angamos_2jugadores.png')
    print(json.dumps(pg.evaluate("({e:H.estado,cam:H.juego.camaras.length,b:H.juego.buques.map(b=>[b.nombre,Math.round(b.hp)])})"),ensure_ascii=False))
    # forzar fin para capturar resultado
    pg.evaluate("H.juego.nivel.restante=0.1;H.debug.pasos=6"); pg.wait_for_timeout(6000); pg.evaluate("H.debug.pasos=1"); pg.screenshot(path=C+'15_resultado_final.png')
    print(pg.evaluate('H.estado')); pg.keyboard.press('Enter'); pg.wait_for_timeout(1000); pg.screenshot(path=C+'16_puntajes.png')
    pg.click('#pPuntajes .volver'); pg.click('[data-ir="DUELO"]'); pg.wait_for_timeout(400); pg.keyboard.press('Enter'); pg.wait_for_timeout(1200)
    pg.keyboard.down('KeyW'); pg.keyboard.down('ArrowUp'); pg.evaluate("H.debug.pasos=6"); pg.wait_for_timeout(4000); pg.evaluate("H.debug.pasos=1"); pg.keyboard.press('Enter'); pg.keyboard.press('Space'); pg.wait_for_timeout(700)
    pg.screenshot(path=C+'17_duelo_1v1.png')
