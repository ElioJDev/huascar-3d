    print(json.dumps(pg.evaluate("({e:H.estado,v:H.DUELO.victorias,r:H.DUELO.ronda,b:H.juego.buques.map(b=>[b.nombre,Math.round(b.hp)])})"),ensure_ascii=False))
    pg.evaluate("H.juego.humanos[1].recibirDano(999,H.juego.humanos[1].pos,H.juego.humanos[0])"); pg.wait_for_timeout(9000); pg.evaluate("H.debug.pasos=1"); pg.screenshot(path=C+'18_duelo_resultado.png')
    print(pg.evaluate('H.estado'), pg.evaluate("document.getElementById('resTitulo').textContent"))
    print('ERRORES', errs)
    b.close()
